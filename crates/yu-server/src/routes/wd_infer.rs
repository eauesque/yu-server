    #[tokio::test]
    async fn infer_rejects_when_scan_roots_is_empty() {
        // fail-closed方針への変更: 従来は空 scan_rootsで無条件許可だったが、
        // 本タスク以降は空scan_rootsで常に拒否(403)する。
        let dir = std::env::temp_dir().join("wd-infer-empty-scanroots-test");
        std::fs::create_dir_all(&dir).unwrap();
        let file_path = dir.join("test.png");
        std::fs::write(&file_path, b"fake").unwrap();

        // scan_rootsは空(既定)のまま呼び出す
        let state = test_state(json!({})).await;
        let body = InferRequest {
            path: file_path.to_str().unwrap().to_string(),
            model_id: "wd_vit_v3".to_string(),
            general_thr: 0.35,
            character_thr: 0.85,
        };
        let response = infer(axum::extract::State(state), axum::Json(body))
            .await
            .into_response();
        assert_eq!(response.status(), axum::http::StatusCode::FORBIDDEN);

        std::fs::remove_file(&file_path).ok();
    }
